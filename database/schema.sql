
-- Vehicle Renting System
-- Database structure

CREATE TABLE IF NOT EXISTS vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_code VARCHAR(20) UNIQUE NOT NULL,
    brand VARCHAR(80) NOT NULL,
    model VARCHAR(100) NOT NULL,
    category VARCHAR(20)
        CHECK (
            category IS NULL
            OR category IN ('Car', 'Bike', 'SUV', 'Van')
        ),
    daily_rate NUMERIC(10, 2) NOT NULL
        CHECK (daily_rate >= 0),
    seats INTEGER NOT NULL DEFAULT 2
        CHECK (seats > 0),
    engine_cc INTEGER
        CHECK (engine_cc IS NULL OR engine_cc > 0),
    image_url TEXT,
    description TEXT,
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    email VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_code VARCHAR(30) UNIQUE NOT NULL,
    customer_id BIGINT NOT NULL
        REFERENCES customers(id),
    vehicle_id BIGINT NOT NULL
        REFERENCES vehicles(id),
    pickup_date DATE NOT NULL,
    return_date DATE NOT NULL,
    daily_rate NUMERIC(10, 2) NOT NULL
        CHECK (daily_rate >= 0),
    total_amount NUMERIC(10, 2) NOT NULL
        CHECK (total_amount >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'Pending'
        CHECK (status IN (
            'Pending', 'Confirmed', 'Active',
            'Completed', 'Cancelled'
        )),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (return_date > pickup_date)
);

CREATE INDEX IF NOT EXISTS idx_bookings_vehicle_dates
    ON bookings (vehicle_id, pickup_date, return_date);

CREATE INDEX IF NOT EXISTS idx_bookings_customer
    ON bookings (customer_id);
